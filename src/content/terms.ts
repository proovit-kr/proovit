import type { PolicyArticle, PolicyBlock } from "./privacy";

/** 약관은 장(章)으로 한 겹 더 묶인다. 방침에는 없는 층이다 */
export interface TermsChapter {
  /** 앵커 id의 근거. 시안은 `tm-1` … `tm-7`을 쓴다 */
  no: number;
  /** 시안 `.n`에 들어가는 표기 — "1장", 부칙은 "부칙" */
  label: string;
  title: string;
  articles: PolicyArticle[];
}

export interface Terms {
  version: string;
  effectiveDate: string;
  chapters: TermsChapter[];
  /**
   * 부칙의 운영자 정보 표. **머리행이 없다** — 시안은 항목 이름을 왼쪽
   * `<th>`로 세우고 값을 `<td>`에 둔다. 정본의 「항목 / 내용」 머리행은
   * 그래서 옮기지 않았다.
   */
  operatorInfo: { rows: [string, string][] };
  /**
   * 부칙 본문. 정본은 두 항이지만 시안은 한 단락에 두 문장으로 그린다 —
   * 시행일과 그 경과 규정이라 나눌 자리가 아니다.
   */
  addendum: string;
}

