/* 시안이 약관을 규칙과 같은 모양으로 그린다 — `.em` 조각과 `<br>` 한 단락 */
import type { RuleLine } from "./rules";

export interface TermsChapter {
  /** 앵커 id의 근거. 시안은 `tm-1` … `tm-7`을 쓴다 */
  no: number;
  /** 시안 `.n`에 들어가는 표기 — "1장", 부칙은 "부칙" */
  label: string;
  title: string;
  /** `<br>`로 나뉘는 줄들. 시안은 한 장을 `<p>` 하나에 넣는다 */
  lines: RuleLine[];
}

export interface Terms {
  version: string;
  effectiveDate: string;
  /** 칩 옆 회색 배지 */
  badge: string;
  chapters: TermsChapter[];
  /**
   * 부칙의 운영자 정보 표. **머리행이 없다** — 시안은 항목 이름을 왼쪽
   * `<th>`로 세우고 값을 `<td>`에 둔다.
   */
  operatorInfo: { rows: [string, string][] };
  /** 부칙 본문. 시안은 한 단락에 두 문장으로 그린다 */
  addendum: string;
}

