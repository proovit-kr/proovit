/**
 * 이용약관 본문.
 *
 * 정본은 노션 「16. 운영규칙서 › 이용약관」이다. privacy.ts·consent.ts와 같은
 * 원칙 — **문구는 팀장 소관이며 개발이 임의로 고치지 않는다.**
 *
 * ## 지금 null인 이유 둘
 *
 * ### 1. 팀장이 아직 게시하지 말라고 했다
 *
 * 노션 「🚀 랜딩 게시용 최종본 (2026-08-31)」의 게시 대상 판정표가 이 문서를
 * **미게시**로 못박았다 — 「회원가입이 없어 이용계약 불성립. 가입 오픈
 * 시점에 게시」. 같은 표에서 개인정보처리방침만 「필수 — 푸터 고정 링크」다.
 *
 * 약관은 게시만으로 계약에 편입되지 않는다. 가입 화면의 동의 절차와 함께
 * 나가야 의미가 있고, 그 전에 올려두면 「동의한 적 없는 약관이 걸려 있는」
 * 상태가 된다.
 *
 * ### 2. 게시용 클린본이 아직 없다
 *
 * 개인정보처리방침은 8/29에 클린본이 나왔는데 약관은 원본만 있고, 그 원본은
 * 첫 조부터 `[상호]` 자리가 비어 있다. 방침 클린본이 확정한 것 둘이 약관에는
 * 아직 반영되지 않았다.
 *
 *   - 호칭: 방침은 「회사」를 버리고 **「PROOVIT 운영자 이윤서(이하 운영자)」**로
 *     통일했다. 약관은 아직 전부 「회사」다. 두 문서가 같은 주체를 다르게
 *     부르면 어느 쪽이 계약 당사자인지가 흐려진다.
 *   - 상호·사업자등록번호·주소: 사업자등록 전까지 표기하지 않기로 했다.
 *     약관의 `[상호]`는 그 결정에 맞춰 다시 써야 하는 자리다.
 *
 * ## 게시 트리거
 *
 * 노션 문서가 적어 둔 예약 트리거 1번이다 — **회원가입 오픈 → 이용약관,
 * 게시물 운영 정책 게시(+폼 문안 B, 만 14세 확인)**. 그때 팀장이 클린본을
 * 만들면 이 파일만 채우면 된다.
 *
 * 값이 들어오는 순간 `/terms`가 열리고 푸터 링크도 함께 살아난다. 다른
 * 파일은 손댈 필요가 없다 — Turnstile 키가 없으면 위젯을 건너뛰는 것과
 * 같은 방식이다.
 */

import type { PolicyArticle } from "./privacy";

/** 약관은 장(章)으로 한 겹 더 묶인다. 방침에는 없는 층이다 */
export interface TermsChapter {
  /** 앵커 id의 근거. 시안은 `tm-1` … `tm-7`을 쓴다 */
  no: number;
  /** 시안 `.n`에 들어가는 표기 — "1장", 부칙은 "부칙" */
  label: string;
  title: string;
  articles: PolicyArticle[];
}

export interface Terms {
  version: string;
  effectiveDate: string;
  chapters: TermsChapter[];
  /** 부칙의 운영자 정보 표 */
  operatorInfo: { head: string[]; rows: string[][] };
}

/**
 * 확정되면 여기에 정본을 옮긴다. 그때까지는 `null` — 라우트도 링크도 죽어 있다.
 *
 * 개정할 때는 `version`과 `effectiveDate`를 반드시 함께 올린다.
 */
export const TERMS: Terms | null = null;
