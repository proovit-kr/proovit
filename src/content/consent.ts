export interface ConsentTableRow {
  /** 수집 항목 */
  item: string;
  /** 수집·이용 목적 */
  purpose: string;
  /**
   * 보유·이용 기간.
   * D3에 따라 화면에서 굵게 표시한다 — 법이 "중요한 내용"으로 지정한 항목이다.
   */
  period: string;
}

export interface ConsentItem {
  /**
   * 폼 필드명이자 서버가 받는 키.
   * 화면마다 항목이 달라 문자열로 둔다 — 사전 신청은 privacy·age·marketing,
   * 참가 신청은 privacy·terms·metrics다.
   */
  key: string;
  required: boolean;
  /** 체크박스 옆 한 줄. 앞의 [필수]/[선택] 표기를 포함한다 */
  label: string;
  /** 펼쳤을 때 보이는 본문 */
  body?: string;
  /*
    「보기」를 펼침이 아니라 **링크**로 만든다. 시안의 `.see`는 두 곳 모두
    `<a class="see" href="#privacy">`라 원래 이동이 정본이다(#scr-auth 1590행,
    #scr-landing 1458행).

    화면마다 갈리는 이유는 폼을 떠나는 값이 다르기 때문이다. 가입 화면은
    체크박스 둘뿐이라 다녀와도 잃을 것이 없다. 랜딩 사전신청 폼은 히어로
    안에 있고 이메일을 이미 적은 상태라 떠나면 그것이 날아간다 — 거기는
    아직 펼침으로 둔다(윤서 확인 대기).
  */
  policyHref?: string;
  table?: ConsentTableRow[];
  /** 표 아래 덧붙는 문장들 */
  notes?: string[];
}

