/** 표 하나. 머리행과 본문행의 열 수는 같아야 한다. */
export interface PolicyTable {
  head: string[];
  rows: string[][];
  /** 표 아래 붙는 단서. 원본의 "※ …" 줄 */
  note?: string;
}

export type PolicyBlock =
  | { kind: "para"; text: string }
  | { kind: "list"; ordered?: boolean; items: string[] }
  | { kind: "table"; table: PolicyTable };

export interface PolicyArticle {
  /** "제1조" — 목차 앵커(`#pv-1`)의 근거가 되므로 번호만 따로 받는다 */
  no: number;
  title: string;
  /**
   * 목차에 적을 짧은 이름. 정본 머리의 「목차:」 줄에 있는 그대로다.
   *
   * ⚠️ 조 제목 전문을 목차에 쓰면 안 된다. ≤1024에서 목차가 가로로 눕는데
   * (시안 `.ru-toc`), 긴 이름이 열여덟 줄로 늘어나 390에서 첫 화면을 통째로
   * 먹는다. 시안의 목차 이름도 짧다(「1. 처리 목적」).
   *
   * 없으면 제목을 그대로 쓴다 — 규칙 문서(rules.ts)가 아직 그렇다.
   */
  short?: string;
  blocks: PolicyBlock[];
}

export interface PrivacyPolicy {
  /** 제18조 ③의 버전 표기 */
  version: string;
  /**
   * 시행일. 제18조 ①이 명시를 요구한다.
   * 시안이 `시행 2026-08-31`로 찍으므로 그 표기를 쓴다.
   */
  effectiveDate: string;
  /** 운영 주체. 정본이 「회사」가 아니라 「운영자」로 통일했다 */
  operator: string;
  /** 머리말 — "…에 따라 다음과 같이 개인정보 처리방침을 수립·공개합니다" */
  preamble: string;
  /** 「주요 개인정보 처리 표시 (요약)」 */
  summary: PolicyTable;
  articles: PolicyArticle[];
}

const para = (text: string): PolicyBlock => ({ kind: "para", text });
const table = (head: string[], rows: string[][], note?: string): PolicyBlock => ({
  kind: "table",
  table: { head, rows, note },
});
const list = (items: string[], ordered = false): PolicyBlock => ({
  kind: "list",
  ordered,
  items,
});

