/**
 * 개인정보처리방침 본문.
 *
 * 원본은 팀장(이윤서)의 「16. 운영규칙서」 제6장 하위 「개인정보처리방침」이다.
 * consent.ts와 같은 원칙 — **문구는 팀장 소관이며 개발이 임의로 고치지 않는다.**
 * 여기 있는 것은 그 원본을 화면에 옮긴 사본이다.
 *
 * ## 지금 null인 이유
 *
 * 원본에 아직 값이 안 들어간 자리가 남아 있다(아래 목록). 반쯤 채운 방침을
 * 게재하는 건 안 하느니만 못하다 — 특히 **제7조(국외 이전) 표가 비면 법
 * 제28조의8 제1항 제3호의 "방침 공개로 별도 동의를 갈음" 요건이 깨진다.**
 * 그러면 방침을 올려두고도 국외 이전의 근거가 없는 상태가 된다.
 *
 * 그래서 값이 다 차기 전까지 `null`로 두고, `/privacy`는 404를 내며 푸터·동의
 * 폼의 링크도 렌더하지 않는다. Turnstile 키가 없으면 위젯을 통째로 건너뛰는
 * 것과 같은 방식이다 — 도입 전에는 지금과 똑같이 동작해야 배포가 안전하다.
 *
 * **값이 오면 이 파일만 채우면 게재된다.** 다른 파일은 손댈 필요가 없다.
 *
 * ## 팀장 확정 대기 중인 빈칸
 *
 * 1. 시행일 — 제목 아래 + 제18조 ①. 두 곳이 같아야 한다
 * 2. 상호 — 첫 문단의 `[상호]`
 * 3. 제14조 보호책임자 연락처 — `[이메일]` / `[전화]`
 * 4. 제9조 ② 미이용 기간 — `[24]`개월
 * 5. 제5조 제3자 제공 표 — 스폰서 미확정이면 표째로 삭제하도록 원본에 적혀 있다
 * 6. 제6조 위탁 표 / 제7조 국외 이전 표 → **아래 주석의 실측값 참고**
 *
 * ## 제6·7조 표에 들어갈 실제 인프라 (2026-08-09 코드·설정 기준, 개발 확인)
 *
 * 이 표는 개발만 알 수 있어서 따로 적어둔다. 원본 문서의 가정과 다른 곳이 있다.
 *
 * | 대상 | 처리하는 개인정보 | 소재 | 원본 문서와 다른 점 |
 * |---|---|---|---|
 * | Vercel Inc. | 접속 IP·이용 기록 (호스팅) | 미국 | — |
 * | Neon (AWS `ap-southeast-1`) | 이메일, 동의 로그 | **싱가포르** | 원본은 `[미국]`으로 적혀 있다 |
 * | Google LLC (GA4) | 쿠키·기기·접속 정보 | 미국 | — |
 * | Cloudflare, Inc. (Turnstile) | **방문자 IP** | 미국 | **원본 표에 없다.** 8/8 도입분 |
 * | Upstash (레이트리밋) | **IP**(제한 키로 저장) | **싱가포르** (`ap-southeast-1`) | **원본 표에 없다** |
 *
 * 즉 국외 이전처는 미국 3곳 + 싱가포르 2곳이다. 원본은 전부 `[미국]`으로 가정하고 있다.
 *
 * - Turnstile은 `src/lib/turnstile.ts`가 siteverify에 `remoteip`를 붙여 보낸다
 * - Upstash는 `src/lib/ratelimit.ts`가 IP를 키로 써서 창(window) 동안 보관한다
 * - ⚠️ **Upstash 리전은 콘솔(Settings → Manage Regions) 값이 정본이다.**
 *   2026-08-09 확인: 리전은 싱가포르 하나뿐이고 read replica가 없다 → 복제도 없다.
 *   REST 엔드포인트를 DNS로 풀면 `ap-northeast-1`(도쿄)이 나오는데 그건 접속 경로(엣지)이지
 *   저장 리전이 아니다. **DNS로 리전을 판단하지 말 것.**
 *   나중에 read 리전을 추가하면 그 나라도 제7조 표에 들어가야 하고, 제6조 ③이
 *   "수탁자 변경 시 지체 없이 공개"를 요구하므로 리전 추가는 곧 방침 개정 사유다
 * - 메일 발송 서비스는 **아직 도입 전이다.** 붙일 때 이 표와 제6조에 함께 추가할 것
 * - 리드에 IP를 저장하지는 않는다(문안 A의 수집 항목이 이메일뿐이라 최소수집 위반).
 *   위 IP 처리는 방침 제2조 3항 "자동으로 생성·수집되는 항목"이 이미 덮는다
 */

/** 표 하나. 머리행과 본문행의 열 수는 같아야 한다. */
export interface PolicyTable {
  head: string[];
  rows: string[][];
  /** 표 아래 붙는 단서. 원본의 "※ …" 줄 */
  note?: string;
}

export type PolicyBlock =
  | { kind: "para"; text: string }
  | { kind: "list"; ordered?: boolean; items: string[] }
  | { kind: "table"; table: PolicyTable };

export interface PolicyArticle {
  /** "제1조" — 목차 앵커(`#article-1`)의 근거가 되므로 번호만 따로 받는다 */
  no: number;
  title: string;
  blocks: PolicyBlock[];
}

export interface PrivacyPolicy {
  /** 제18조 ③의 버전 표기. "v3.0" */
  version: string;
  /**
   * 시행일. 제18조 ①이 명시를 요구한다.
   * 화면에 그대로 찍히므로 원본 표기(`2026. 8. 12.`)를 그대로 옮긴다.
   */
  effectiveDate: string;
  /** 첫 문단의 `[상호]` 자리 */
  operator: string;
  /** 머리말 — "…에 따라 다음과 같이 개인정보 처리방침을 수립·공개합니다" */
  preamble: string;
  /** 「주요 개인정보 처리 표시 (요약)」 */
  summary: PolicyTable;
  articles: PolicyArticle[];
}

/**
 * 확정되면 여기에 원본을 옮긴다. 그때까지는 `null` — 라우트도 링크도 죽어 있다.
 *
 * 개정할 때는 `version`과 `effectiveDate`를 반드시 함께 올린다. 제18조 ②가
 * 시행 7일 전(중대 변경은 30일 전) 공지를 요구하므로 시행일을 미래로 두고
 * 먼저 배포하는 것도 가능하다 — 그 판단은 팀장 몫이다.
 */
export const PRIVACY_POLICY: PrivacyPolicy | null = null;
