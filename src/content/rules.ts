/** 본문에서 한 단계 밝히는 조각. 시안 `.em` */
export type RuleSegment = string | { em: string };

/** `<br>`로 나뉘는 한 줄. 시안은 세 줄을 한 단락 안에 넣는다(3. 심사 기준) */
export type RuleLine = RuleSegment[];

export type RuleBlock =
  | { kind: "para"; lines: RuleLine[] }
  | { kind: "list"; items: string[] };

export interface RuleSection {
  /** 앵커. 시안 `ru-1` … `ru-6` — 리더보드와 푸터가 `#ru-4`를 건다 */
  id: string;
  /** 제목 앞 번호. 시안 `.n` */
  n: string;
  title: string;
  blocks: RuleBlock[];
}

export interface SeasonRules {
  version: string;
  effectiveDate: string;
  /** 칩 옆 라임 배지. 근거는 4번 꼭지가 아니라 정본 제3조 ③이다 */
  badge: string;
  sections: RuleSection[];
}

